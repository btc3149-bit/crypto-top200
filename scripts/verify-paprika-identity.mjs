// scripts/verify-paprika-identity.mjs — 第七期 F7-01 Paprika 落库身份复核（可复现）
// 对 data/coins.json 的全部 paprikaId 逐条做身份复核：Paprika /v1/coins 目录中
// 该 id 必须存在、symbol 全等（trim+大写）、且规范化 name 全等或命中已知别名表
// （shared/paprika-identity.js，与 fetcher 门禁同一口径）。仅 symbol+价差不再算证据。
// 同时产出四项计数（mapped / identityValid / activeUsable / tickerHit，tickerHit
// 须 tickers 存在且报价有效、市值交叉合理性通过）并按门禁（四项均 ≥94%=188/200，
// 阈值单一事实源 shared/paprika-identity.js，F8-21）给结论。
//
// 第八期 F8-01：本脚本同时是「身份登记册」的生成者——
//   node scripts/verify-paprika-identity.mjs --write-registry [--coins-file ..] [--tickers-file ..]
// 经全名复核通过的条目写入 workers/fetcher/src/paprika-registry.js（入仓提交）；
// fetcher 运行时以登记册身份为准（不再自洽比对）。普通复核模式下同时校验已入仓
// 登记册与 data/coins.json 的一致性（diffPaprikaRegistry），不一致即 exit 1。
// 登记册新鲜度另由 tests/paprika-gate.test.mjs 在部署门禁中强制校验。
// 用法：node scripts/verify-paprika-identity.mjs [--coins-file <缓存/v1/coins.json>]
//       [--tickers-file <缓存 tickers.json>]（缺省实时拉 Paprika 公开 API 各 1 次）
// 退出码：任一已映射条目身份不符 → 1；四项计数未达门禁 → 1（Paprika 保持关闭为预期）；
//         登记册与币表不一致 → 1。
// F8-29：纯逻辑已抽为可导出函数（buildRegistryEntries/checkRegistryConsistency/
// summarizeGate），离线套件 tests/paprika-verify-scripts.test.mjs 以 fixture 覆盖；
// 仅直接执行本文件时才走 main（读文件/拉 API/写登记册）。
import { readFileSync, writeFileSync } from "node:fs";
import { decodeCoins } from "./decode-coins.mjs";
import {
  countPaprikaGateStats,
  paprikaIdentityMatch,
  buildPaprikaRegistry,
  diffPaprikaRegistry,
  evaluatePaprikaGate,
} from "../shared/paprika-identity.js";

// 登记册条目生成（纯函数）：coins 为带 name/symbol/snapshotMcapUsd 的本地币表。
export function buildRegistryEntries(coins, directory) {
  return buildPaprikaRegistry(coins, directory);
}

// 登记册一致性校验（纯函数）：返回不一致描述列表，空数组 = 一致。
export function checkRegistryConsistency(coins, registryEntries) {
  return diffPaprikaRegistry(coins, registryEntries);
}

// 四项计数 + 门禁结论（纯函数）。
export function summarizeGate(coins, directory, tickers, registryEntries) {
  const stats = countPaprikaGateStats(coins, directory, tickers, { registry: registryEntries || undefined });
  const gate = evaluatePaprikaGate(stats, coins.length);
  return { stats, gate };
}

export function renderRegistryModule(entries, generatedAtIso) {
  const sorted = [...entries].sort((a, b) => String(a.cgId).localeCompare(String(b.cgId)));
  return [
    "// workers/fetcher/src/paprika-registry.js — Paprika 身份登记册（F8-01）",
    "// AUTO-GENERATED by scripts/verify-paprika-identity.mjs --write-registry，请勿手改。",
    "// 生成口径：data/coins.json 全部 paprikaId 经 Paprika /v1/coins 目录全名身份复核",
    "// （symbol 全等 + 规范化 name 全等/已知别名，shared/paprika-identity.js）通过后入册；",
    "// fetcher preflight 以本册 CG 侧 name/symbol 与实时目录比对，不再自洽校验。",
    `// Generated: ${generatedAtIso}`,
    `export const PAPRIKA_REGISTRY_GENERATED_AT = ${JSON.stringify(generatedAtIso)};`,
    `export const PAPRIKA_IDENTITY_REGISTRY = ${JSON.stringify(sorted, null, 1)};`,
    "",
  ].join("\n");
}

function argFile(flag) {
  const i = process.argv.indexOf(flag);
  return i >= 0 ? process.argv[i + 1] : null;
}
async function loadJson(flag, url) {
  const f = argFile(flag);
  if (f) return JSON.parse(readFileSync(f, "utf-8"));
  const res = await fetch(url);
  if (!res.ok) throw new Error(`fetch ${url} -> ${res.status}`);
  return res.json();
}

async function main() {
  const writeRegistry = process.argv.includes("--write-registry");
  const coinsData = JSON.parse(readFileSync(new URL("../data/coins.json", import.meta.url), "utf-8"));
  const coins = decodeCoins(coinsData).map((c) => ({
    id: c.coingeckoId,
    name: c.name,
    symbol: c.symbol,
    snapshotMcapUsd: c.snapshotMcapUsd,
    paprikaId: c.paprikaId,
  }));
  const directory = await loadJson("--coins-file", "https://api.coinpaprika.com/v1/coins");
  const tickers = await loadJson("--tickers-file", "https://api.coinpaprika.com/v1/tickers?quotes=USD&limit=5000");
  if (!Array.isArray(directory) || !Array.isArray(tickers)) throw new Error("paprika payload invalid");

  const { entries, failures: registryFailures } = buildRegistryEntries(coins, directory);

  if (writeRegistry) {
    if (registryFailures.length) {
      console.error(`REGISTRY NOT WRITTEN: ${registryFailures.length} mapped entries fail full-name identity review`);
      for (const f of registryFailures) console.error(`- ${f.id} (${f.paprikaId}) reason=${f.reason}`);
      process.exitCode = 1;
      return;
    }
    const text = renderRegistryModule(entries, new Date().toISOString());
    writeFileSync(new URL("../workers/fetcher/src/paprika-registry.js", import.meta.url), text);
    console.log(`registry written: ${entries.length} entries -> workers/fetcher/src/paprika-registry.js`);
  }

  // 已入仓登记册（--write-registry 时即刚写入的同一批条目）与币表一致性校验。
  let registryEntries = entries;
  if (!writeRegistry) {
    try {
      const mod = await import("../workers/fetcher/src/paprika-registry.js");
      registryEntries = mod.PAPRIKA_IDENTITY_REGISTRY;
    } catch {
      console.error("REGISTRY MISSING: workers/fetcher/src/paprika-registry.js not found; run with --write-registry");
      process.exitCode = 1;
      return;
    }
    const problems = checkRegistryConsistency(coins, registryEntries);
    if (problems.length) {
      console.error(`REGISTRY STALE: ${problems.length} inconsistencies with data/coins.json`);
      for (const p of problems) console.error(`- ${p}`);
      process.exitCode = 1;
    } else {
      console.log(`registry consistency: OK (${registryEntries.length} entries)`);
    }
  }

  const { stats, gate } = summarizeGate(coins, directory, tickers, registryEntries);
  const dirById = new Map(directory.map((e) => [e.id, e]));
  const identityFailures = stats.failures.filter((f) => f.stage === "identity");

  console.log(`paprika directory=${directory.length} tickers=${tickers.length} total=${stats.total}`);
  console.log(`mapped=${stats.mapped} identityValid=${stats.identityValid} activeUsable=${stats.activeUsable} tickerHit=${stats.tickerHit}`);
  console.log(`gate(94%): threshold=${gate.threshold} ok=${gate.ok}${gate.ok ? "" : " failures: " + gate.failures.join("; ")}`);
  for (const f of stats.failures) {
    const e = dirById.get(f.paprikaId);
    console.log(`- ${f.id} (${f.paprikaId}) stage=${f.stage} reason=${f.reason}${e ? ` paprikaName=${JSON.stringify(e.name)} paprikaSymbol=${JSON.stringify(e.symbol)} active=${e.is_active} rank=${e.rank}` : " (not in directory)"}`);
  }
  for (const x of stats.plausibilityExceptions) {
    console.log(`plausibility-exception ${x.id} (${x.paprikaId}) mcapRatio=${x.ratio.toExponential(2)} (registered exception, see shared/paprika-identity.js)`);
  }
  // 逐条身份明细（via 标注证据类型：name / alias / symbol-prefix）
  for (const c of coins) {
    if (!c.paprikaId) continue;
    const m = paprikaIdentityMatch(c, dirById.get(c.paprikaId));
    if (m.ok && m.via === "alias") console.log(`alias-accept ${c.id} -> ${c.paprikaId} (local name ${JSON.stringify(c.name)} vs directory ${JSON.stringify(dirById.get(c.paprikaId)?.name)})`);
  }
  if (identityFailures.length) {
    console.error(`IDENTITY FAIL: ${identityFailures.length} mapped entries fail identity review`);
    process.exitCode = 1;
  }
  if (!gate.ok) process.exitCode = 1;
}

const isMain = process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href;
if (isMain) {
  await main();
}
